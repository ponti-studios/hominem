#!/usr/bin/env bash
# Builds this checkout once and installs two commands around that one binary:
#   hominem-local  -> your local API, its own home (~/.hominem-local), no real bank creds
#   hominem-prod   -> the production API, your usual home (~/.hominem), REAL data
# Override the local API with HOMINEM_LOCAL_API_URL. Re-run to pick up code changes.
set -euo pipefail

cli_dir="$(cd "$(dirname "$0")/.." && pwd)"
bin_dir="$HOME/.local/bin"
binary="$HOME/.local/lib/hominem-profiles/hominem"
local_url="${HOMINEM_LOCAL_API_URL:-$(cd "$cli_dir/../.." && pnpm exec portless get api)}"
prod_url="https://api.ponti.io"

mkdir -p "$bin_dir" "$(dirname "$binary")"
# Its own copy, so the post-commit hook rebuilding `hominem` leaves these alone.
# No .env autoload: whatever folder you're in can't sneak settings into a profile.
(cd "$cli_dir" && bun build --compile --no-compile-autoload-dotenv --loader .py:text \
  src/index.ts --outfile "$binary")

# write_wrapper <name> <home folder under $HOME> <api url> [extra shell line]
write_wrapper() {
  cat >"$bin_dir/$1" <<WRAPPER
#!/usr/bin/env bash
# Generated by packages/cli/scripts/install-profiles.sh. Re-run that instead of editing.
export HOMINEM_HOME="\$HOME/$2"
export HOMINEM_API_URL="$3"
unset HOMINEM_AGENT_ENV_FILE HOMINEM_AGENT_WEALTH_DIR
${4:-}
exec "$binary" "\$@"
WRAPPER
  chmod +x "$bin_dir/$1"
  echo "Installed $1 -> $3 (home: ~/$2)"
}

# Local only: drop bank creds your shell exports (put sandbox ones in ~/.hominem-local/env),
# and trust the portless certificate so https://*.lvh.me works.
write_wrapper hominem-local .hominem-local "$local_url" \
  'unset STARLING_API_TOKEN PLAID_CLIENT_ID PLAID_SECRET PLAID_ACCESS_TOKEN PLAID_ENV
[ -f "$HOME/.portless/ca.pem" ] && export NODE_EXTRA_CA_CERTS="$HOME/.portless/ca.pem"'
write_wrapper hominem-prod .hominem "$prod_url"
