const coveredCountries = new Set<string>(MANAGED_PAYMENTS_TAX_COUNTRY_CODES);

export function isManagedPaymentsTaxCountry(countryCode: string): boolean {
  return coveredCountries.has(countryCode.trim().toUpperCase());
}

